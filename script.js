function showElement(element) {
  element.classList.add("is-visible");
  element.querySelectorAll("path").forEach((path) => path.classList.add("drawn"));
}

if (!reducedMotion) {
  document.body.classList.add("motion-ready");

  const revealItems = [...document.querySelectorAll(revealSelector)];
  revealItems.forEach((element, index) => {
    element.dataset.reveal = "";
    element.style.setProperty("--reveal-delay", `${Math.min((index % 4) * 75, 225)}ms`);
  });

  const drawings = [...document.querySelectorAll(drawingSelector)];
  drawings.forEach((drawing) => {
    drawing.classList.add("hand-drawn");
    drawing.querySelectorAll("path").forEach((path, index) => {
      const length = path.getTotalLength();
      path.style.strokeDasharray = `${length}px`;
      path.style.strokeDashoffset = `${length}px`;
      path.style.transitionDuration = `${Math.min(1900, Math.max(650, length * 1.15))}ms`;
      path.style.transitionDelay = `${Math.min(index * 45, 360)}ms`;
    });
  });

  if ("IntersectionObserver" in window) {
    const observer = new IntersectionObserver((entries, currentObserver) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          showElement(entry.target);
          currentObserver.unobserve(entry.target);
        }
      });
    }, { threshold: 0.14, rootMargin: "0px 0px -35px 0px" });

    revealItems.forEach((element) => observer.observe(element));
    drawings.forEach((element) => observer.observe(element));
  } else {
    [...revealItems, ...drawings].forEach(showElement);
  }
}

const scrollProgress = document.querySelector("#scroll-progress-fill");
let scrollUpdateQueued = false;
function updateScrollProgress() {
  const scrollableHeight = document.documentElement.scrollHeight - window.innerHeight;
  const progress = scrollableHeight > 0 ? (window.scrollY / scrollableHeight) * 100 : 0;
  scrollProgress.style.width = `${progress}%`;
  document.body.classList.toggle("is-scrolled", document.querySelector(".hero").getBoundingClientRect().bottom <= document.querySelector(".site-header").offsetHeight + 24);
  scrollUpdateQueued = false;
}

window.addEventListener("scroll", () => {
  if (scrollUpdateQueued) return;
  scrollUpdateQueued = true;
  window.requestAnimationFrame(updateScrollProgress);
}, { passive: true });

updateScrollProgress();

