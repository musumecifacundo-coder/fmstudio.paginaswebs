function setLanguage(language) {
  const copy = translations[language] ?? translations.es;
  document.documentElement.lang = language;
  document.title = copy["page-title"];
  document.querySelector('meta[name="description"]').content = copy["page-description"];
  document.querySelector(".main-nav").setAttribute("aria-label", copy["nav-label"]);
  document.querySelector(".language-switch").setAttribute("aria-label", copy["language-label"]);
  document.querySelector(".hero-art").setAttribute("aria-label", copy["art-label"]);
  document.querySelector("#hero-art-title").textContent = copy["hero-art-title"];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value !== undefined) element.innerHTML = value;
  });

  document.querySelectorAll("[data-language]").forEach((button) => {
    const isActive = button.dataset.language === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  try {
    localStorage.setItem("fmstudio-language", language);
  } catch {
    // The page still works when browser storage is unavailable.
  }
}

document.querySelectorAll("[data-language]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

document.querySelector("#year").textContent = new Date().getFullYear();

try {
  const savedLanguage = localStorage.getItem("fmstudio-language");
  if (savedLanguage === "en") setLanguage("en");
} catch {
  // Spanish is the default language.
}

